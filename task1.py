num = int(input("Введите число: "))

if num % 2 == 0: # Если число делится на 2 без остатка, то оно четное
    print(f"Число {num} - чётное")
else:
    print(f"Число {num} - нечётное")
 # Доп. Деление на 3
print(f"Число {num} - делится на 3" if num % 3 == 0 else f"Число {num} - не делится на 3")
# Доп. Отрицательное или нет
print(f"Число {num} - отрицательное" if num < 0 else f"Число {num} - положительное" if num > 0 else f"Число {num} - равно нулю")
